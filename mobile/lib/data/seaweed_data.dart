  static SeaweedInfo? findById(String id) {
    for (final seaweed in seaweeds) {
      if (seaweed.id == id) {
        return seaweed;
      }
    }

    return null;
  }

  static SeaweedInfo? findByClassificationLabel(String label) {
    final normalizedLabel = label.trim().toLowerCase();

    for (final seaweed in seaweeds) {
      final scientificName =
          seaweed.scientificName.trim().toLowerCase();

      final englishName =
          seaweed.englishName.trim().toLowerCase();

      final filipinoName =
          seaweed.filipinoName.trim().toLowerCase();

      final bisayaName =
          seaweed.bisayaName.trim().toLowerCase();

      if (normalizedLabel == scientificName ||
          normalizedLabel == englishName ||
          normalizedLabel == filipinoName ||
          normalizedLabel == bisayaName) {
        return seaweed;
      }
    }

    return null;
  }

