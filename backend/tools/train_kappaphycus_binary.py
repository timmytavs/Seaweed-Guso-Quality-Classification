"""Fine-tune gUSo's seven-species MobileNetV3 Small as KAPPAPHYCUS vs OTHER_SEAWEED.

Automatically excludes identical same-label validation files from evaluation;
rejects training/validation leakage and conflicting labels. Original data unchanged.

From the backend directory:
    python -m tools.train_kappaphycus_binary --epochs 8 --batch-size 8

Requires the manifests generated by File 88 in backend/reports/.
Keeps existing species and quality checkpoints unchanged; creates a NEW checkpoint.
OTHER_SEAWEED does not include unrelated/non-seaweed images in this dataset.
"""

import argparse
import csv
import hashlib
import json
import os
import random
from collections import Counter, defaultdict
from pathlib import Path

import torch
import torch.nn as nn
from PIL import Image, UnidentifiedImageError
from torch.utils.data import DataLoader, Dataset
from torchvision import models, transforms

BASE = Path(__file__).resolve().parents[1]  # backend/
LABELS = ("OTHER_SEAWEED", "KAPPAPHYCUS")
CLASS_TO_IDX = {name: idx for idx, name in enumerate(LABELS)}
MEAN = [0.485, 0.456, 0.406]
STD = [0.229, 0.224, 0.225]


def sha256(path: Path) -> str:
    result = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1024 * 1024), b""):
            result.update(chunk)
    return result.hexdigest()


def read_rows(path: Path, split: str) -> list[dict]:
    if not path.is_file():
        raise FileNotFoundError(f"Missing manifest: {path}. Run File 88 first.")
    with path.open(newline="", encoding="utf-8-sig") as fh:
        reader = csv.DictReader(fh)
        required = {"image_path", "label", "class_index", "source_species", "split"}
        if not reader.fieldnames or not required.issubset(reader.fieldnames):
            raise ValueError(f"Unexpected CSV header in {path}")
        rows = list(reader)
    if not rows:
        raise ValueError(f"Empty manifest: {path}")
    for row in rows:
        if row["split"] != split:
            raise ValueError(f"Invalid split in {path}: {row['split']}")
        if row["label"] not in CLASS_TO_IDX or row["class_index"] != str(CLASS_TO_IDX[row["label"]]):
            raise ValueError(f"Class-index mismatch in {path}: {row}")
        if (row["source_species"] == "KAPPAPHYCUS") != (row["label"] == "KAPPAPHYCUS"):
            raise ValueError(f"Source species contradicts binary label: {row}")
        image_path = Path(row["image_path"])
        if not image_path.is_file():
            raise FileNotFoundError(f"Dataset image missing: {image_path}")
    return rows


def clean_splits_and_check_leakage(train: list[dict], val: list[dict]):
    """Remove exact same-label duplicates within splits; reject cross-split overlap.

    Returns cleaned train, cleaned validation, training duplicate count,
    and a full list of removed validation duplicates for the training report.
    The source CSVs and photographs are never modified.
    """
    train_by_hash = {}
    unique_train = []
    duplicates = 0
    for index, row in enumerate(train, start=1):
        digest = sha256(Path(row["image_path"]))
        old = train_by_hash.get(digest)
        if old is not None:
            if old["label"] != row["label"]:
                raise ValueError("Contradictory training labels for identical image bytes")
            duplicates += 1
        else:
            train_by_hash[digest] = row
            unique_train.append(row)
        if index % 5000 == 0:
            print(f"  Hashed training images: {index}/{len(train)}", flush=True)
    seen_val = {}
    unique_val = []
    removed_val = []
    for row in val:
        digest = sha256(Path(row["image_path"]))
        if digest in train_by_hash:
            raise ValueError(
                "TRAIN/VALIDATION LEAK: "
                f"{train_by_hash[digest]['image_path']} and {row['image_path']}"
            )
        earlier = seen_val.get(digest)
        if earlier is not None:
            # Identical image data assigned opposing labels cannot be fixed by
            # automatic de-duplication; investigate the source annotations.
            if (earlier["label"] != row["label"] or
                    earlier["source_species"] != row["source_species"]):
                raise ValueError(
                    "Conflicting validation labels for identical image data: "
                    f"{earlier['image_path']} ({earlier['source_species']}) and "
                    f"{row['image_path']} ({row['source_species']}). "
                    "Correct the labels before training."
                )
            removed_val.append({
                "kept_path": earlier["image_path"],
                "excluded_path": row["image_path"],
                "source_species": row["source_species"],
                "sha256": digest,
            })
            continue
        seen_val[digest] = row
        unique_val.append(row)
    return unique_train, unique_val, duplicates, removed_val


class ManifestImages(Dataset):
    def __init__(self, rows: list[dict], augment: bool):
        self.rows = rows
        steps = [transforms.Resize((224, 224))]
        if augment:
            steps += [
                transforms.RandomHorizontalFlip(),
                transforms.RandomVerticalFlip(),
                transforms.RandomRotation(15),
                transforms.ColorJitter(brightness=0.15, contrast=0.15),
            ]
        steps += [transforms.ToTensor(), transforms.Normalize(MEAN, STD)]
        self.transform = transforms.Compose(steps)

    def __len__(self):
        return len(self.rows)

    def __getitem__(self, index: int):
        row = self.rows[index]
        with Image.open(row["image_path"]) as img:
            image = self.transform(img.convert("RGB"))
        return image, int(row["class_index"]), row["source_species"]


def create_model(source_checkpoint: Path):
    if not source_checkpoint.is_file():
        raise FileNotFoundError(f"Seven-species checkpoint not found: {source_checkpoint}")
    checkpoint = torch.load(source_checkpoint, map_location="cpu", weights_only=True)
    required = {"num_classes", "classes", "class_to_idx", "model_state_dict"}
    if not isinstance(checkpoint, dict) or not required.issubset(checkpoint):
        raise ValueError("The original species checkpoint lacks expected metadata.")
    classes = checkpoint["classes"]
    if (
        not isinstance(classes, (tuple, list))
        or len(classes) != checkpoint["num_classes"]
        or "KAPPAPHYCUS" not in classes
        or dict(checkpoint["class_to_idx"]) != {name: i for i, name in enumerate(classes)}
    ):
        raise ValueError("Invalid seven-species class metadata; do not guess class indices.")
    model = models.mobilenet_v3_small(weights=None)
    features = model.classifier[3].in_features
    model.classifier[3] = nn.Linear(features, len(classes))
    model.load_state_dict(checkpoint["model_state_dict"], strict=True)
    # Keep the learned seaweed-specific backbone, retrain the last layer for 2 classes.
    model.classifier[3] = nn.Linear(features, 2)
    return model


def metrics_from_predictions(actual: list[int], predicted: list[int]):
    tn = sum(a == 0 and p == 0 for a, p in zip(actual, predicted))
    fp = sum(a == 0 and p == 1 for a, p in zip(actual, predicted))
    fn = sum(a == 1 and p == 0 for a, p in zip(actual, predicted))
    tp = sum(a == 1 and p == 1 for a, p in zip(actual, predicted))
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    specificity = tn / (tn + fp) if tn + fp else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return {
        "tn": tn, "fp": fp, "fn": fn, "tp": tp,
        "precision_kappaphycus": round(precision, 5),
        "recall_kappaphycus": round(recall, 5),
        "specificity_other_seaweed": round(specificity, 5),
        "f1_kappaphycus": round(f1, 5),
        "balanced_accuracy": round((recall + specificity) / 2, 5),
        "overall_accuracy": round((tn + tp) / len(actual), 5),
    }


def validate(model, loader, device, use_amp):
    model.eval()
    actual, predicted = [], []
    by_species = defaultdict(lambda: [0, 0])  # total, incorrect
    with torch.inference_mode():
        for images, labels, source_species in loader:
            images = images.to(device, non_blocking=True)
            with torch.autocast(device_type="cuda", enabled=use_amp):
                outputs = model(images)
            choices = outputs.argmax(dim=1).cpu().tolist()
            expected = labels.tolist()
            actual.extend(expected)
            predicted.extend(choices)
            for name, truth, result in zip(source_species, expected, choices):
                by_species[name][0] += 1
                by_species[name][1] += int(truth != result)
    return metrics_from_predictions(actual, predicted), dict(by_species)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--train-csv", type=Path, default=BASE / "reports/kappaphycus_binary_train.csv")
    parser.add_argument("--val-csv", type=Path, default=BASE / "reports/kappaphycus_binary_validation.csv")
    parser.add_argument("--source", type=Path, default=BASE / "app/ml/weights/species_mobilenetv3_best.pth")
    parser.add_argument("--output", type=Path, default=BASE / "app/ml/weights/kappaphycus_binary_mobilenetv3_best.pth")
    parser.add_argument("--epochs", type=int, default=8)
    parser.add_argument("--batch-size", type=int, default=8)
    parser.add_argument("--learning-rate", type=float, default=0.0001)
    parser.add_argument("--patience", type=int, default=3)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--overwrite", action="store_true", help="Explicitly replace an existing binary checkpoint")
    args = parser.parse_args()
    if min(args.epochs, args.batch_size, args.patience) < 1 or args.learning_rate <= 0:
        parser.error("epochs, batch-size, patience and learning-rate must be positive")
    output = args.output.resolve()
    source = args.source.resolve()
    if output == source:
        parser.error("Output checkpoint MUST differ from the seven-species source")
    if output.exists() and not args.overwrite:
        parser.error(f"Output already exists: {output}. Use --overwrite only intentionally.")
    random.seed(args.seed)
    torch.manual_seed(args.seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(args.seed)
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    use_amp = device.type == "cuda"
    print(f"Device: {device}; mixed precision: {use_amp}", flush=True)
    if use_amp:
        print("GPU:", torch.cuda.get_device_name(0), flush=True)
    print("Reading and checking manifests ...", flush=True)
    train = read_rows(args.train_csv, "train")
    validation = read_rows(args.val_csv, "validation")
    original_validation_size = len(validation)
    train, validation, discarded, removed_validation = (
        clean_splits_and_check_leakage(train, validation)
    )
    train_counts = Counter(row["label"] for row in train)
    val_counts = Counter(row["label"] for row in validation)
    if any(train_counts[name] == 0 or val_counts[name] == 0 for name in LABELS):
        raise ValueError("Both classes must exist in train and validation splits")
    print(f"Training: {dict(train_counts)} ({discarded} repeated files removed)", flush=True)
    print(
        f"Validation: {dict(val_counts)} "
        f"({len(removed_validation)} identical repeated files excluded; "
        f"{len(validation)}/{original_validation_size} unique images retained)",
        flush=True,
    )
    if removed_validation:
        print("Validation duplicate examples (excluded -> retained):", flush=True)
        for entry in removed_validation[:5]:
            print(f"  {entry['excluded_path']} -> {entry['kept_path']}", flush=True)
        if len(removed_validation) > 5:
            print(f"  ... and {len(removed_validation) - 5} more", flush=True)
    print("NOTE: Hash checks cannot detect augmented/cropped versions of the same original image.", flush=True)
    print("NOTE: OTHER_SEAWEED has no unrelated non-seaweed photographs.", flush=True)

    train_ds = ManifestImages(train, augment=True)
    val_ds = ManifestImages(validation, augment=False)
    train_loader = DataLoader(train_ds, batch_size=args.batch_size, shuffle=True, num_workers=0, pin_memory=use_amp)
    val_loader = DataLoader(val_ds, batch_size=args.batch_size, shuffle=False, num_workers=0, pin_memory=use_amp)
    model = create_model(source).to(device)
    optimizer = torch.optim.AdamW(model.parameters(), lr=args.learning_rate, weight_decay=0.0001)
    scheduler = torch.optim.lr_scheduler.CosineAnnealingLR(optimizer, T_max=args.epochs)
    criterion = nn.CrossEntropyLoss()
    scaler = torch.amp.GradScaler("cuda", enabled=use_amp)
    best_balanced = -1.0
    best_f1 = -1.0
    bad_epochs = 0
    output.parent.mkdir(parents=True, exist_ok=True)
    report_path = BASE / "reports/kappaphycus_binary_training_results.json"
    history = []

    for epoch in range(1, args.epochs + 1):
        model.train()
        total_loss = 0.0
        total_samples = 0
        for images, labels, _ in train_loader:
            images = images.to(device, non_blocking=True)
            labels = labels.to(device, non_blocking=True)
            optimizer.zero_grad(set_to_none=True)
            with torch.autocast(device_type="cuda", enabled=use_amp):
                outputs = model(images)
                loss = criterion(outputs, labels)
            scaler.scale(loss).backward()
            scaler.step(optimizer)
            scaler.update()
            total_loss += loss.item() * labels.size(0)
            total_samples += labels.size(0)
        scheduler.step()
        val_metrics, by_species = validate(model, val_loader, device, use_amp)
        loss_value = total_loss / total_samples
        record = {"epoch": epoch, "train_loss": round(loss_value, 5), **val_metrics, "source_species_errors": by_species}
        history.append(record)
        print(
            f"Epoch {epoch}/{args.epochs} | train loss {loss_value:.4f} | "
            f"balanced acc {100 * val_metrics['balanced_accuracy']:.2f}% | "
            f"KAPPAPHYCUS precision {100 * val_metrics['precision_kappaphycus']:.2f}% | "
            f"recall {100 * val_metrics['recall_kappaphycus']:.2f}% | "
            f"F1 {100 * val_metrics['f1_kappaphycus']:.2f}% | "
            f"TN={val_metrics['tn']} FP={val_metrics['fp']} "
            f"FN={val_metrics['fn']} TP={val_metrics['tp']}",
            flush=True,
        )
        # Select the best by balanced accuracy, then positive-class F1 on ties.
        balanced = val_metrics["balanced_accuracy"]
        f1 = val_metrics["f1_kappaphycus"]
        if balanced > best_balanced or (balanced == best_balanced and f1 > best_f1):
            best_balanced, best_f1 = balanced, f1
            bad_epochs = 0
            checkpoint = {
                "model_state_dict": {k: v.detach().cpu() for k, v in model.state_dict().items()},
                "model_name": "mobilenet_v3_small_binary",
                "num_classes": 2,
                "classes": list(LABELS),
                "class_to_idx": CLASS_TO_IDX,
                "image_size": 224,
                "normalization_mean": MEAN,
                "normalization_std": STD,
                "epoch": epoch,
                "validation_metrics": val_metrics,
                "validation_species_errors": by_species,
                "source_checkpoint": str(source),
                "training_class_counts": dict(train_counts),
                "validation_class_counts": dict(val_counts),
                "removed_validation_duplicates": len(removed_validation),
                "seed": args.seed,
                "note": "OTHER_SEAWEED negatives exclude unrelated/non-seaweed photos. Validate on independent capture sessions before deployment.",
            }
            temp_path = output.with_name(output.name + ".tmp")
            torch.save(checkpoint, temp_path)
            os.replace(temp_path, output)
            print(f"  Saved best binary checkpoint: {output}", flush=True)
        else:
            bad_epochs += 1
            if bad_epochs >= args.patience:
                print(f"Early stopping: no improvement for {args.patience} epochs.", flush=True)
                break
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(json.dumps({
        "classes": CLASS_TO_IDX,
        "source_checkpoint": str(source),
        "binary_checkpoint": str(output),
        "train_counts": dict(train_counts),
        "validation_counts": dict(val_counts),
        "removed_train_duplicates": discarded,
        "original_validation_image_count": original_validation_size,
        "removed_validation_duplicates": len(removed_validation),
        "validation_duplicate_details": removed_validation,
        "best_balanced_accuracy": best_balanced,
        "best_f1_kappaphycus": best_f1,
        "epochs": history,
        "evaluation_limitations": [
            "Only exact duplicates were checked, not augmented/near duplicates.",
            "Negative examples include other seaweeds, not unrelated objects.",
            "Validation originally contained 50 KAPPAPHYCUS and 300 OTHER_SEAWEED images; actual unique-image counts are reported above.",
            "An independent capture-session test set is still required.",
        ],
    }, indent=2), encoding="utf-8")
    print(f"\nBest checkpoint: {output}", flush=True)
    print(f"Detailed training report: {report_path}", flush=True)
    print("No existing gUSo model loader, API, database, or previous checkpoint was modified.", flush=True)


if __name__ == "__main__":
    main()
